assert.equal(bind('int32 wcdb_set_my_account_id(int64 h,const char* id)')(handle, 'fixture_me'), 0);
assert.equal(get(bind('int32 wcdb_get_sessions(int64 h,_Out_ void** out)'), handle)[0].username, session);
assert.equal(get(bind('int32 wcdb_get_contact(int64 h,const char* username,_Out_ void** out)'), handle, session).remark, 'Test Friend');
assert.equal(get(bind('int32 wcdb_get_display_names(int64 h,const char* users,_Out_ void** out)'), handle, JSON.stringify(['fixture_null'])).fixture_null, 'fixture_null');
assert.equal(get(bind('int32 wcdb_get_contact(int64 h,const char* username,_Out_ void** out)'), handle, "' OR 1=1--"), null);
const messages = bind('int32 wcdb_get_messages(int64 h,const char* session,int32 limit,int32 offset,_Out_ void** out)');
assert.deepEqual(get(messages, handle, session, 10, 0).map(row => row.local_id), [3, 2, 1]);
assert.deepEqual(get(messages, handle, session, 10, 0).map(row => row.message_content), ['第三条', 'second', 'first']);
assert.deepEqual(get(messages, handle, session, 1, 1).map(row => row.local_id), [2]);
const countOut = [0];
assert.equal(bind('int32 wcdb_get_message_count(int64 h,const char* session,_Out_ int32* out)')(handle, session, countOut), 0);
assert.equal(countOut[0], 3);
const cursorOut = [0];
assert.equal(bind('int32 wcdb_open_message_cursor(int64 h,const char* session,int32 batch,int32 ascending,int32 begin,int32 end,_Out_ int64* out)')(handle, session, 2, 1, 0, 0, cursorOut), 0);
const fetch = bind('int32 wcdb_fetch_message_batch(int64 h,int64 cursor,_Out_ void** out,_Out_ int32* more)');
const readBatch = () => {
  const out = [null], more = [0];
  assert.equal(fetch(handle, cursorOut[0], out, more), 0);
  const result = JSON.parse(koffi.decode(out[0], 'char', -1)); free(out[0]);
  return { result, more: more[0] };
};
const first = readBatch(), second = readBatch();
