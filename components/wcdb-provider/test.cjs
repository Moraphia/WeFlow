const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const { execFileSync } = require('node:child_process');
const koffi = require('koffi');
const root = path.resolve(__dirname, '../..');
const base = fs.mkdtempSync(path.join(root, '.deployment/independent-fixture-'));
const session = 'fixture_friend';
const hash = crypto.createHash('md5').update(session).digest('hex');
execFileSync(path.join(__dirname, 'build/Release/create_fixture.exe'), [base, hash], { windowsHide: true });
const sessionDb = path.join(base, 'db_storage/session/session.db');
assert.notEqual(fs.readFileSync(sessionDb).subarray(0, 16).toString(), 'SQLite format 3\0');
const lib = koffi.load(path.join(root, 'resources/local-wcdb/win32/x64/weflow_wcdb_provider.dll'));
const bind = signature => lib.func(signature);
const free = bind('void wcdb_free_string(void* ptr)');
const get = (fn, ...args) => {
  const out = [null];
  const status = fn(...args, out);
  let value;
  if (out[0]) { try { value = JSON.parse(koffi.decode(out[0], 'char', -1)); } finally { free(out[0]); } }
  assert.equal(status, 0, 'Native operation failed');
  return value;
};
const open = bind('int32 wcdb_open_account(const char* path,const char* key,_Out_ int64* out)');
const shutdown = bind('int32 wcdb_shutdown()');
const logs = bind('int32 wcdb_get_logs(_Out_ void** out)');
const query = bind('int32 wcdb_exec_query(int64 h,const char* kind,const char* path,const char* sql,_Out_ void** out)');
assert.equal(bind('int32 wcdb_init()')(), 0);
const handleOut = [0];
assert.equal(open(sessionDb, '01'.repeat(32), handleOut), 0, JSON.stringify(get(logs)));
const handle = handleOut[0];
